function love.conf(t)
    t.window.title = "Procedural Character Animation"
    t.window.width = 800
    t.window.height = 600
    t.window.vsync = 1
    t.window.resizable = true
    t.window.minwidth = 400
    t.window.minheight = 300

    t.console = true  -- Enable console on Windows for debugging
end
